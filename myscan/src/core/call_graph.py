"""Call Graph builder for MyScan Enterprise SAST platform.

Builds a function-level call graph from Python AST analysis and
determines reachability from entry points.
"""

from __future__ import annotations

import ast
import os
from collections import deque
from dataclasses import dataclass, field
from typing import Optional, Union

ENTRY_POINT_PATTERNS = {
    "function_names": {
        "main", "app", "application", "handle_request", "handler",
        "run", "start", "cli",
    },
    "decorators": {
        "app.route", "app.get", "app.post", "app.put", "app.delete",
        "app.patch", "app.options",
        "router.get", "router.post", "router.put", "router.delete",
        "router.patch", "router.options",
        "Blueprint", "Flask", "FastAPI",
        "app.before_request", "app.after_request",
        "app.errorhandler", "app.before_first_request",
        "router.api_view", "router.viewset",
        "celery.task", "task",
    },
}

DANGEROUS_CALLS = {
    "eval", "exec", "compile", "__import__",
    "os.system", "os.popen",
    "subprocess.run", "subprocess.call", "subprocess.Popen",
    "subprocess.check_output", "subprocess.check_call",
    "shell_exec",
    "pexpect.spawn",
    "os.exec", "os.execl", "os.execle", "os.execlp", "os.execv",
    "os.execvp", "os.execvpe",
}

DANGEROUS_SINKS = {
    "execute", "raw", "cursor.execute", "render_template_string",
    "pickle.loads", "pickle.load", "yaml.load",
    "marshal.loads", "marshal.load",
    "shelve.open",
    "jsonpickle.decode",
    "requests.get", "requests.post", "requests.put", "requests.delete",
    "urllib.request.urlopen",
    "tempfile.mktemp",
    "open",
}

USER_INPUT_PATTERNS = {
    "input", "request.form", "request.args", "request.json",
    "request.data", "request.values", "request.cookies",
    "request.headers", "request.files",
    "sys.argv", "os.environ",
    "stdin", "sys.stdin",
    "getenv",
    "environ.get", "environ[",
    "raw_input",
}

BUILTIN_FUNCTIONS = {
    "print", "len", "range", "str", "int", "float", "bool", "list",
    "dict", "set", "tuple", "type", "isinstance", "issubclass",
    "hasattr", "getattr", "setattr", "delattr", "callable",
    "id", "hash", "repr", "abs", "min", "max", "sum", "sorted",
    "reversed", "enumerate", "zip", "map", "filter", "reduce",
    "any", "all", "next", "iter", "super", "property", "staticmethod",
    "classmethod", "open", "input", "hex", "oct", "bin", "chr", "ord",
    "format", "divmod", "pow", "round", "complex", "bytearray", "bytes",
    "memoryview", "frozenset", "object", "Exception", "ValueError",
    "TypeError", "KeyError", "IndexError", "AttributeError",
    "ImportError", "RuntimeError", "StopIteration", "OSError",
    "FileNotFoundError", "PermissionError",
}

TEST_FILE_PATTERNS = (
    "test_", "_test.py", "tests.py", "test.py",
    "conftest.py", "pytest", "unittest",
)

AUTO_GENERATED_PATTERNS = (
    "# generated", "# auto-generated", "# autogenerated",
    "# DO NOT EDIT", "# This file is auto-generated",
    "# Generated by", "# noqa",
)

DEPRECATED_MARKERS = (
    "@deprecated", "DeprecationWarning", "warnings.warn",
    "# deprecated",
)


@dataclass
class CallEdge:
    caller: str
    callee: str
    caller_file: str
    callee_file: str = ""
    line: int = 0
    is_builtin: bool = False

    def to_dict(self) -> dict:
        return {
            "caller": self.caller,
            "callee": self.callee,
            "caller_file": self.caller_file,
            "callee_file": self.callee_file,
            "line": self.line,
            "is_builtin": self.is_builtin,
        }


@dataclass
class FunctionNode:
    name: str
    file_path: str = ""
    line_start: int = 0
    line_end: int = 0
    is_entry_point: bool = False
    is_test: bool = False
    callees: list[str] = field(default_factory=list)
    callers: list[str] = field(default_factory=list)
    imports: list[str] = field(default_factory=list)
    has_user_input: bool = False
    has_dangerous_sink: bool = False

    @property
    def key(self) -> str:
        return f"{self.file_path}:{self.name}"

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "file_path": self.file_path,
            "line_start": self.line_start,
            "line_end": self.line_end,
            "is_entry_point": self.is_entry_point,
            "is_test": self.is_test,
            "callees": list(self.callees),
            "callers": list(self.callers),
            "imports": list(self.imports),
            "has_user_input": self.has_user_input,
            "has_dangerous_sink": self.has_dangerous_sink,
            "key": self.key,
        }


class CallGraph:
    def __init__(self) -> None:
        self._functions: dict[str, FunctionNode] = {}
        self._edges: list[CallEdge] = []
        self._file_cache: dict[str, str] = {}

    def _make_key(self, file_path: str, name: str) -> str:
        return f"{file_path}:{name}"

    def _is_test_file(self, file_path: str) -> bool:
        basename = os.path.basename(file_path)
        return any(pat in basename for pat in TEST_FILE_PATTERNS)

    def _is_auto_generated(self, source: str) -> bool:
        lines = source.splitlines()[:30]
        header = "\n".join(lines)
        return any(marker.lower() in header.lower() for marker in AUTO_GENERATED_PATTERNS)

    def _is_deprecated(self, source: str) -> bool:
        return any(marker.lower() in source.lower() for marker in DEPRECATED_MARKERS)

    def _get_decorator_name(self, node: ast.expr) -> Optional[str]:
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Attribute):
            parts = []
            current: ast.expr = node
            while isinstance(current, ast.Attribute):
                parts.append(current.attr)
                current = current.value
            if isinstance(current, ast.Name):
                parts.append(current.id)
            parts.reverse()
            return ".".join(parts)
        if isinstance(node, ast.Call):
            return self._get_decorator_name(node.func)
        return None

    def _is_entry_decorator(self, decorators: list[ast.expr]) -> bool:
        for deco in decorators:
            name = self._get_decorator_name(deco)
            if name is None:
                continue
            if name in ENTRY_POINT_PATTERNS["decorators"]:
                return True
            for pattern in ENTRY_POINT_PATTERNS["decorators"]:
                if name.startswith(pattern + "."):
                    return True
        return False

    def _resolve_callee_name(self, node: ast.expr) -> Optional[str]:
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Attribute):
            parts: list[str] = []
            current: ast.expr = node
            while isinstance(current, ast.Attribute):
                parts.append(current.attr)
                current = current.value
            if isinstance(current, ast.Name):
                parts.append(current.id)
            parts.reverse()
            return ".".join(parts)
        return None

    def _extract_imports(self, tree: ast.Module) -> list[str]:
        imports: list[str] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    imports.append(alias.asname or alias.name)
            elif isinstance(node, ast.ImportFrom):
                module = node.module or ""
                for alias in node.names:
                    full = f"{module}.{alias.name}" if module else alias.name
                    imports.append(alias.asname or full)
        return imports

    def _scan_for_user_input(self, tree: ast.Module) -> bool:
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                name = self._resolve_callee_name(node.func)
                if name is None:
                    continue
                for pattern in USER_INPUT_PATTERNS:
                    if name == pattern or name.startswith(pattern + "."):
                        return True
            elif isinstance(node, ast.Name):
                if node.id in ("request", "sys", "os", "stdin", "environ"):
                    return True
        return False

    def _scan_for_dangerous_sinks(self, tree: ast.Module) -> bool:
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                name = self._resolve_callee_name(node.func)
                if name is None:
                    continue
                if name in DANGEROUS_SINKS or name in DANGEROUS_CALLS:
                    return True
                for sink in DANGEROUS_SINKS:
                    if name.endswith("." + sink):
                        return True
                for dangerous in DANGEROUS_CALLS:
                    if name.endswith("." + dangerous):
                        return True
        return False

    def _is_dangerous_call(self, name: str) -> bool:
        if name in DANGEROUS_CALLS:
            return True
        for dangerous in DANGEROUS_CALLS:
            if name.endswith("." + dangerous):
                return True
        return False

    def _extract_functions(
        self,
        tree: ast.Module,
        file_path: str,
        source: str,
    ) -> dict[str, FunctionNode]:
        functions: dict[str, FunctionNode] = {}
        is_test = self._is_test_file(file_path)

        for node in ast.iter_child_nodes(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                fn = self._analyze_function(node, file_path, is_test)
                functions[fn.key] = fn
            elif isinstance(node, ast.ClassDef):
                for item in ast.iter_child_nodes(node):
                    if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        fn = self._analyze_function(item, file_path, is_test)
                        functions[fn.key] = fn

        has_user_input = self._scan_for_user_input(tree)
        has_dangerous_sink = self._scan_for_dangerous_sinks(tree)

        for fn in functions.values():
            if has_user_input:
                fn.has_user_input = True
            if has_dangerous_sink:
                fn.has_dangerous_sink = True

        return functions

    def _analyze_function(
        self,
        node: Union[ast.FunctionDef, ast.AsyncFunctionDef],
        file_path: str,
        is_test: bool,
    ) -> FunctionNode:
        name = node.name
        line_start = node.lineno
        line_end = node.end_lineno or node.lineno

        is_entry = name in ENTRY_POINT_PATTERNS["function_names"]
        if not is_entry:
            is_entry = self._is_entry_decorator(node.decorator_list)

        callees = self._extract_callees(node)

        has_user_input = self._function_has_user_input(node)
        has_dangerous_sink = self._function_has_dangerous_sink(node)

        return FunctionNode(
            name=name,
            file_path=file_path,
            line_start=line_start,
            line_end=line_end,
            is_entry_point=is_entry,
            is_test=is_test or name.startswith("test_"),
            callees=callees,
            callers=[],
            imports=[],
            has_user_input=has_user_input,
            has_dangerous_sink=has_dangerous_sink,
        )

    def _extract_callees(self, node: Union[ast.FunctionDef, ast.AsyncFunctionDef]) -> list[str]:
        callees: list[str] = []
        for child in ast.walk(node):
            if isinstance(child, ast.Call):
                callee_name = self._resolve_callee_name(child.func)
                if callee_name is not None:
                    callees.append(callee_name)
        return callees

    def _function_has_user_input(self, node: Union[ast.FunctionDef, ast.AsyncFunctionDef]) -> bool:
        for child in ast.walk(node):
            if isinstance(child, ast.Call):
                name = self._resolve_callee_name(child.func)
                if name is None:
                    continue
                for pattern in USER_INPUT_PATTERNS:
                    if name == pattern or name.startswith(pattern + "."):
                        return True
            elif isinstance(child, ast.Name):
                if child.id in ("request", "sys", "os", "stdin", "environ"):
                    return True
        return False

    def _function_has_dangerous_sink(self, node: Union[ast.FunctionDef, ast.AsyncFunctionDef]) -> bool:
        for child in ast.walk(node):
            if isinstance(child, ast.Call):
                name = self._resolve_callee_name(child.func)
                if name is None:
                    continue
                if name in DANGEROUS_SINKS or name in DANGEROUS_CALLS:
                    return True
                for sink in DANGEROUS_SINKS:
                    if name.endswith("." + sink):
                        return True
                for dangerous in DANGEROUS_CALLS:
                    if name.endswith("." + dangerous):
                        return True
        return False

    def _build_edges(self, file_path: str, functions: dict[str, FunctionNode]) -> list[CallEdge]:
        edges: list[CallEdge] = []
        for fn in functions.values():
            for callee_name in fn.callees:
                is_builtin = callee_name in BUILTIN_FUNCTIONS
                callee_file = ""
                target_key = self._find_function_key(callee_name, file_path)
                if target_key and target_key in functions:
                    callee_file = file_path
                elif target_key and target_key in self._functions:
                    callee_file = self._functions[target_key].file_path
                elif "." not in callee_name:
                    callee_file = file_path

                edge = CallEdge(
                    caller=fn.name,
                    callee=callee_name,
                    caller_file=file_path,
                    callee_file=callee_file,
                    line=fn.line_start,
                    is_builtin=is_builtin,
                )
                edges.append(edge)

                if target_key and target_key in self._functions:
                    target_fn = self._functions[target_key]
                    if fn.name not in target_fn.callers:
                        target_fn.callers.append(fn.name)

        return edges

    def _find_function_key(self, name: str, current_file: str) -> Optional[str]:
        direct = self._make_key(current_file, name)
        if direct in self._functions:
            return direct
        for key, fn in self._functions.items():
            if fn.name == name and fn.file_path == current_file:
                return key
        base_name = name.rsplit(".", 1)[-1] if "." in name else name
        for key, fn in self._functions.items():
            if fn.name == base_name:
                return key
        return None

    def analyze_file(self, file_path: str, content: str) -> None:
        try:
            tree = ast.parse(content, filename=file_path)
        except SyntaxError:
            return

        self._file_cache[file_path] = content

        functions = self._extract_functions(tree, file_path, content)

        imports = self._extract_imports(tree)
        for fn in functions.values():
            fn.imports = imports

        for key, fn in functions.items():
            if key not in self._functions:
                self._functions[key] = fn
            else:
                existing = self._functions[key]
                existing.callees = fn.callees
                existing.has_user_input = existing.has_user_input or fn.has_user_input
                existing.has_dangerous_sink = existing.has_dangerous_sink or fn.has_dangerous_sink

        edges = self._build_edges(file_path, functions)
        self._edges.extend(edges)

    def analyze_repository(self, repo_path: str) -> None:
        for root, dirs, files in os.walk(repo_path):
            dirs[:] = [
                d for d in dirs
                if d not in (".git", "__pycache__", "node_modules", ".tox", "venv", ".venv", "env")
            ]
            for filename in files:
                if not filename.endswith(".py"):
                    continue
                file_path = os.path.join(root, filename)
                try:
                    with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                        content = f.read()
                except (OSError, IOError):
                    continue
                normalized = file_path.replace("\\", "/")
                self.analyze_file(normalized, content)

        self._resolve_cross_file_callees()

    def _resolve_cross_file_callees(self) -> None:
        import_keys = set()
        for fn in self._functions.values():
            for imp in fn.imports:
                import_keys.add(imp)

        for fn in self._functions.values():
            for callee_name in list(fn.callees):
                if callee_name in BUILTIN_FUNCTIONS:
                    continue
                if self._find_function_key(callee_name, fn.file_path) is not None:
                    continue
                base_name = callee_name.rsplit(".", 1)[-1] if "." in callee_name else callee_name
                for key, target_fn in self._functions.items():
                    if target_fn.name == base_name:
                        edge = CallEdge(
                            caller=fn.name,
                            callee=callee_name,
                            caller_file=fn.file_path,
                            callee_file=target_fn.file_path,
                            line=fn.line_start,
                            is_builtin=False,
                        )
                        self._edges.append(edge)
                        if fn.name not in target_fn.callers:
                            target_fn.callers.append(fn.name)
                        break

    def get_entry_points(self) -> list[FunctionNode]:
        return [fn for fn in self._functions.values() if fn.is_entry_point]

    def get_callers(self, function_name: str) -> list[FunctionNode]:
        result: list[FunctionNode] = []
        for fn in self._functions.values():
            if fn.name == function_name or fn.name.endswith("." + function_name):
                result.extend(
                    caller_fn
                    for caller_name in fn.callers
                    if (caller_fn := self._find_function_node(caller_name, fn.file_path)) is not None
                )
        for fn in self._functions.values():
            if fn.name == function_name:
                for caller_name in fn.callers:
                    node = self._find_function_node(caller_name, fn.file_path)
                    if node is not None and node not in result:
                        result.append(node)
        return result

    def get_callees(self, function_name: str) -> list[FunctionNode]:
        result: list[FunctionNode] = []
        for fn in self._functions.values():
            if fn.name == function_name:
                for callee_name in fn.callees:
                    node = self._find_function_node(callee_name, fn.file_path)
                    if node is not None and node not in result:
                        result.append(node)
        return result

    def _find_function_node(self, name: str, current_file: str) -> Optional[FunctionNode]:
        base_name = name.rsplit(".", 1)[-1] if "." in name else name
        for fn in self._functions.values():
            if fn.name == name and fn.file_path == current_file:
                return fn
        for fn in self._functions.values():
            if fn.name == base_name:
                return fn
        return None

    def _build_reverse_adjacency(self) -> dict[str, list[str]]:
        adjacency: dict[str, list[str]] = {key: [] for key in self._functions}
        for edge in self._edges:
            if edge.is_builtin:
                continue
            callee_key = self._find_callee_key(edge)
            caller_key = self._make_key(edge.caller_file, edge.caller)
            if callee_key and callee_key in adjacency:
                if caller_key not in adjacency[callee_key]:
                    adjacency[callee_key].append(caller_key)
        return adjacency

    def _find_callee_key(self, edge: CallEdge) -> Optional[str]:
        direct = self._make_key(edge.callee_file, edge.callee) if edge.callee_file else None
        if direct and direct in self._functions:
            return direct
        base_name = edge.callee.rsplit(".", 1)[-1] if "." in edge.callee else edge.callee
        for key, fn in self._functions.items():
            if fn.name == base_name:
                return key
        return None

    def _build_adjacency(self) -> dict[str, list[str]]:
        adjacency: dict[str, list[str]] = {key: [] for key in self._functions}
        for edge in self._edges:
            if edge.is_builtin:
                continue
            caller_key = self._make_key(edge.caller_file, edge.caller)
            callee_key = self._find_callee_key(edge)
            if caller_key in adjacency and callee_key and callee_key in adjacency:
                if callee_key not in adjacency[caller_key]:
                    adjacency[caller_key].append(callee_key)
        return adjacency

    def _bfs_from_entries(
        self,
        adjacency: dict[str, list[str]],
        reverse: bool = False,
    ) -> set[str]:
        entry_keys = {fn.key for fn in self.get_entry_points()}
        if not entry_keys:
            return set()

        if reverse:
            adj = self._build_reverse_adjacency()
        else:
            adj = adjacency

        visited: set[str] = set()
        queue: deque[str] = deque()

        for key in entry_keys:
            if key in adj:
                queue.append(key)
                visited.add(key)

        while queue:
            current = queue.popleft()
            for neighbor in adj.get(current, []):
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)

        return visited

    def is_reachable_from_entry(self, function_name: str) -> bool:
        adjacency = self._build_adjacency()
        reachable = self._bfs_from_entries(adjacency)

        for key, fn in self._functions.items():
            if fn.name == function_name and key in reachable:
                return True
        return False

    def get_reachability(self, function_name: str) -> str:
        target_keys = [key for key, fn in self._functions.items() if fn.name == function_name]

        if not target_keys:
            return "dead_code"

        for key in target_keys:
            fn = self._functions[key]
            if self._is_auto_generated_function(fn):
                return "generated"
            if self._is_deprecated_function(fn):
                return "deprecated"

        adjacency = self._build_adjacency()
        reachable = self._bfs_from_entries(adjacency)

        any_reachable = any(key in reachable for key in target_keys)
        if any_reachable:
            return "reachable"

        all_test = all(self._functions[key].is_test for key in target_keys)
        if all_test:
            return "test_only"

        return "dead_code"

    def _is_auto_generated_function(self, fn: FunctionNode) -> bool:
        file_path = fn.file_path
        if file_path in self._file_cache:
            content = self._file_cache[file_path]
        else:
            try:
                with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                    content = f.read()
                self._file_cache[file_path] = content
            except (OSError, IOError):
                return False

        lines = content.splitlines()
        start = max(0, fn.line_start - 1)
        end = min(len(lines), fn.line_start + 2)
        header = "\n".join(lines[:end])
        return any(marker.lower() in header.lower() for marker in AUTO_GENERATED_PATTERNS)

    def _is_deprecated_function(self, fn: FunctionNode) -> bool:
        file_path = fn.file_path
        if file_path in self._file_cache:
            content = self._file_cache[file_path]
        else:
            try:
                with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                    content = f.read()
                self._file_cache[file_path] = content
            except (OSError, IOError):
                return False

        lines = content.splitlines()
        start = max(0, fn.line_start - 5)
        end = min(len(lines), fn.line_end)
        region = "\n".join(lines[start:end])
        return any(marker.lower() in region.lower() for marker in DEPRECATED_MARKERS)

    def get_path_from_entry(self, target: str) -> list[str]:
        adjacency = self._build_adjacency()
        entry_keys = {fn.key for fn in self.get_entry_points()}

        target_keys = [key for key, fn in self._functions.items() if fn.name == target]
        if not target_keys:
            return []

        parent: dict[str, Optional[str]] = {key: None for key in self._functions}
        visited: set[str] = set()
        queue: deque[str] = deque()

        for key in entry_keys:
            if key in adjacency:
                queue.append(key)
                visited.add(key)

        found_key: Optional[str] = None
        while queue:
            current = queue.popleft()
            if current in target_keys:
                found_key = current
                break
            for neighbor in adjacency.get(current, []):
                if neighbor not in visited:
                    visited.add(neighbor)
                    parent[neighbor] = current
                    queue.append(neighbor)

        if found_key is None:
            for key in target_keys:
                if key in visited:
                    found_key = key
                    break

        if found_key is None:
            return []

        path: list[str] = []
        current: Optional[str] = found_key
        while current is not None:
            fn = self._functions.get(current)
            if fn:
                label = f"{fn.file_path}:{fn.name}:{fn.line_start}"
                path.append(label)
            current = parent.get(current)

        path.reverse()
        return path

    def get_vulnerable_paths(self) -> list[dict]:
        vulnerable: list[dict] = []
        adjacency = self._build_adjacency()
        reachable = self._bfs_from_entries(adjacency)

        for key, fn in self._functions.items():
            if not fn.has_dangerous_sink:
                continue
            if key not in reachable:
                continue

            path = self.get_path_from_entry(fn.name)
            user_input_in_path = self._path_has_user_input(path)

            vulnerable.append({
                "function": fn.name,
                "file": fn.file_path,
                "line": fn.line_start,
                "path": path,
                "user_input_flows": user_input_in_path,
                "risk": "critical" if user_input_in_path else "high",
            })

        vulnerable.sort(key=lambda v: (0 if v["risk"] == "critical" else 1, v["file"], v["line"]))
        return vulnerable

    def _path_has_user_input(self, path: list[str]) -> bool:
        for entry in path:
            parts = entry.split(":")
            if len(parts) >= 2:
                fn_key = self._make_key(parts[0], parts[1])
                fn = self._functions.get(fn_key)
                if fn and fn.has_user_input:
                    return True
        return False

    def to_dict(self) -> dict:
        return {
            "functions": {key: fn.to_dict() for key, fn in self._functions.items()},
            "edges": [edge.to_dict() for edge in self._edges],
            "entry_points": [fn.to_dict() for fn in self.get_entry_points()],
            "stats": {
                "total_functions": len(self._functions),
                "total_edges": len(self._edges),
                "entry_points": len(self.get_entry_points()),
                "files_analyzed": len({fn.file_path for fn in self._functions.values()}),
                "reachable": sum(
                    1 for fn in self._functions.values()
                    if self.get_reachability(fn.name) == "reachable"
                ),
                "dead_code": sum(
                    1 for fn in self._functions.values()
                    if self.get_reachability(fn.name) == "dead_code"
                ),
                "test_only": sum(
                    1 for fn in self._functions.values()
                    if self.get_reachability(fn.name) == "test_only"
                ),
            },
        }
